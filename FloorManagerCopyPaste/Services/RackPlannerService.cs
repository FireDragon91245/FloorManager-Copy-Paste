    /// <summary>
    /// Repairs the two pieces of live state used by
    /// WaypointInitializationSystem.GetServerProcessingSpeed: the server's prefab
    /// processing capacity and its NetworkMap registration. Save/load happens to fix
    /// both by rebuilding a Server from its prefab; pasted servers need the same state
    /// immediately, including after they are picked up and reinserted.
    /// </summary>
    internal static void RefreshPastedServerRuntimeState(Server server)
    {
        if (!server) return;

        var instanceId = server.GetInstanceID();
        if (!PastedServerCapacityByInstance.TryGetValue(instanceId, out var expectedCapacity))
            return;

        try
        {
            if (expectedCapacity > 0f &&
                float.IsFinite(expectedCapacity) &&
                !Mathf.Approximately(server.maxProcessingSpeed, expectedCapacity))
            {
                server.maxProcessingSpeed = expectedCapacity;
            }
        }
        catch (Exception ex)
        {
            MelonLogger.Warning(
                $"Pasted server capacity repair failed for {server.ServerID ?? "<unknown>"}: {ex.Message}");
        }

        try
        {
            var networkMap = NetworkMap.instance;
            if (networkMap is not null)
            {
                // RegisterRackedServer maintains the rack/server association used by
                // the simulation. RegisterServer maintains the ID lookup used by the
                // route evaluator. Both calls are idempotent dictionary updates.
                networkMap.RegisterRackedServer(server);
                networkMap.RegisterServer(server);

                if (!string.IsNullOrEmpty(server.ServerID))
                {
                    // RegisterServer returns early when its endpoint dictionary
                    // already contains the ID. If an earlier partial registration
                    // happened before NetworkMap's graph dictionary was ready, that
                    // leaves GetServer valid but GetDevice null forever. Cables then
                    // exist visually yet every route evaluates to zero. Fill only the
                    // missing graph node; never remove a live node or its cable edges.
                    if (networkMap.GetDevice(server.ServerID) is null)
                    {
                        networkMap.AddDevice(
                            server.ServerID,
                            (CableLink.TypeOfLink)1,
                            SafeValue(server.GetCustomerID));
                    }

                    networkMap.UpdateDeviceCustomerID(
                        server.ServerID,
                        SafeValue(server.GetCustomerID));
                }
            }
        }
        catch (Exception ex)
        {
            MelonLogger.Warning(
                $"Pasted server NetworkMap repair failed for {server.ServerID ?? "<unknown>"}: {ex.Message}");
        }

        if (!string.IsNullOrEmpty(server.ServerID))
            PastedServerIds.Add(server.ServerID);

        try
        {
            WaypointInitializationSystem.Instance?.RequestRouteEvaluation();
        }
        catch (Exception ex)
        {
            MelonLogger.Warning(
                $"Pasted server route refresh failed for {server.ServerID ?? "<unknown>"}: {ex.Message}");
        }

    }

    /// <summary>
    /// Restores both the serialized power flag and the server's live simulation
    /// membership. ServerInsertedInRack(null) is the fresh-placement path and does
    /// not call TurnOnCommonFunction, even when the prefab's isOn flag is already
    /// true. Calling PowerButton(true) is also incorrect: the boolean is a forced
    /// transition mode, not the desired state, and takes the shutdown branch.
    /// </summary>
    private static void RestoreServerPowerState(Server server, bool shouldBeOn)
    {
        if (!server) return;

        try
        {
            if (shouldBeOn)
                server.TurnOnCommonFunction();
            else
                server.TurnOffCommonFunctions();
        }
        catch (Exception ex)
        {
            MelonLogger.Warning(
                $"Server power-state initialization failed for {server.ServerID ?? "<unknown>"}: {ex.Message}");
        }
    }

    /// <summary>
    /// Runs the live switch lifecycle explicitly. The fresh insert path only creates
    /// and registers the switch ID; the save-load path separately invokes the virtual
    /// TurnOnCommonFunction for powered switches. This also covers Router and Firewall.
    /// </summary>
    private static void RestoreSwitchPowerState(NetworkSwitch networkSwitch, bool shouldBeOn)
    {
        if (!networkSwitch) return;

        try
        {
            if (shouldBeOn)
                networkSwitch.TurnOnCommonFunction();
            else
                networkSwitch.TurnOffCommonFunctions();
        }
        catch (Exception ex)
        {
            MelonLogger.Warning(
                $"Switch power-state initialization failed for {GetSwitchId(networkSwitch)}: {ex.Message}");
        }
    }

    private static RackDeviceTemplate FindBlockingDevice(RackDeviceTemplate template, RackDeviceTemplate[] occupancy)
    {
        RackDeviceTemplate blocking = null;
        for (var i = template.StartIndex; i < template.StartIndex + template.SizeInU; i++)
        {
            var slot = occupancy[i];
            if (slot is null)
                continue;

            if (blocking is null)
                blocking = slot;
            else if (!ReferenceEquals(blocking, slot) && !AreEquivalent(blocking, slot))
                return slot;
        }

        return blocking;
    }

    private static RackDeviceTemplate[] BuildOccupancy(RackRuntimeInfo rackInfo)
    {
        var occupancy = new RackDeviceTemplate[rackInfo.TotalSlots];
        foreach (var device in rackInfo.Devices)
            StampDevice(device, occupancy);

        return occupancy;
    }

    private static void StampDevice(RackDeviceTemplate device, RackDeviceTemplate[] occupancy)
    {
        var upperBound = Math.Min(occupancy.Length, device.StartIndex + Math.Max(1, device.SizeInU));
        for (var i = Math.Max(0, device.StartIndex); i < upperBound; i++)
            occupancy[i] = device;
    }

    private static bool IsWithinRack(RackDeviceTemplate template, int totalSlots)
    {
        return template.StartIndex >= 0 && template.SizeInU > 0 && template.StartIndex + template.SizeInU <= totalSlots;
    }

    private static bool AreEquivalent(RackDeviceTemplate left, RackDeviceTemplate right)
    {
        if (left.Kind != right.Kind ||
            left.StartIndex != right.StartIndex ||
            left.SizeInU != right.SizeInU ||
            left.PrefabId != right.PrefabId)
            return false;

        // A missing array index denotes a legacy template. prefabID + physical
        // size is still a stronger identity than the stale/default variant field.
        return left.PrefabArrayIndex < 0 ||
               right.PrefabArrayIndex < 0 ||
               left.PrefabArrayIndex == right.PrefabArrayIndex;
    }

    private static RackDeviceTemplate CloneDeviceTemplate(RackDeviceTemplate source)
    {
        return new RackDeviceTemplate
        {
            Kind = source.Kind,
            StartIndex = source.StartIndex,
            SizeInU = source.SizeInU,
            PrefabId = source.PrefabId,
            PrefabArrayIndex = source.PrefabArrayIndex,
            VariantId = source.VariantId,
            BasePrice = source.BasePrice,
            DisplayName = source.DisplayName,
            Label = source.Label,
            IsPoweredOn = source.IsPoweredOn,
            ServerType = source.ServerType,
            HasOperationalServerType = source.HasOperationalServerType,
            ServerMaxProcessingSpeed = source.ServerMaxProcessingSpeed,
            PortVlanFilters = (source.PortVlanFilters ?? []).Select(entry => new NetworkPortVlanFilterTemplate
            {
                PortIndex = entry.PortIndex,
                DisallowedVlanIds = [..entry.DisallowedVlanIds ?? []]
            }).ToList(),
            RouterAsn = source.RouterAsn,
            RouterNextRouteId = source.RouterNextRouteId,
            RouterOwnedSubnets = (source.RouterOwnedSubnets ?? []).Select(subnet => new RouterOwnedSubnetTemplate
            {
                VlanId = subnet.VlanId,
                SubnetCidr = subnet.SubnetCidr
            }).ToList(),
            RouterRoutes = (source.RouterRoutes ?? []).Select(route => new RouterRouteTemplate
            {
                RouteId = route.RouteId,
                SourceVlanId = route.SourceVlanId,
                SourceIp = route.SourceIp,
                TargetVlanId = route.TargetVlanId,
                TargetIp = route.TargetIp
            }).ToList(),
            FirewallClusterIp = source.FirewallClusterIp,
            FirewallRules = (source.FirewallRules ?? []).Select(rule => new FirewallRuleTemplate
            {
                PortIndex = rule.PortIndex,
                SourceIpCidr = rule.SourceIpCidr,
                DestinationIpCidr = rule.DestinationIpCidr,
                NetworkPort = rule.NetworkPort,
                Protocol = rule.Protocol,
                Bidirectional = rule.Bidirectional,
                Allow = rule.Allow
            }).ToList(),
            LocalPos = source.LocalPos,
            LocalEuler = source.LocalEuler,
            HasLocalPose = source.HasLocalPose,
            LocalRotationX = source.LocalRotationX,
            LocalRotationY = source.LocalRotationY,
            LocalRotationZ = source.LocalRotationZ,
            LocalRotationW = source.LocalRotationW
        };
    }

    private static string BuildRackLabel(Rack rack, int index)
    {
        var pos = rack.transform.position;
        return $"Rack {index + 1} ({pos.x:0.#}/{pos.z:0.#})";
    }

    private static string SanitizeName(string name)
    {
        var invalid = Path.GetInvalidFileNameChars();
        return new string(name.Select(ch => invalid.Contains(ch) ? '_' : ch).ToArray());
    }

    public static int CalculateAdjustedPrice(int basePrice)
    {
        return Mathf.CeilToInt(basePrice * PriceMultiplier);
    }
