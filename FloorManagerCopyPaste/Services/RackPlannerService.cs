    private static List<RackCableTemplate> CaptureRackCables(Rack sourceRack, List<DeviceWithRuntime> rackDevices)
    {
        var cables = new List<RackCableTemplate>();
        if (rackDevices is null || rackDevices.Count == 0 || !sourceRack)
        {
            return cables;
        }

        // Map every CableLink in the rack to its (deviceIndex, portIndex)
        var linkLookup = new Dictionary<CableLink, (int deviceIndex, int portIndex, RackDeviceKind kind)>();
        for (var i = 0; i < rackDevices.Count; i++)
        {
            var d = rackDevices[i];
            var ports = GetCableLinkPorts(d);
            if (ports is null) continue;
            for (var p = 0; p < ports.Count; p++)
            {
                var link = ports[p];
                if (!link)
                {
                    continue;
                }

                if (!linkLookup.ContainsKey(link))
                    linkLookup[link] = (i, p, d.Template.Kind);
            }
        }

        // Group by cable id
        var byCable = new Dictionary<int, List<(CableLink link, int devIdx, int port, RackDeviceKind kind)>>();
        foreach (var kv in linkLookup)
        {
            var link = kv.Key;
            int cableId;
            try
            {
                cableId = link.cableIDsOnLink;
            }
            catch
            {
                continue;
            }

            if (cableId <= 0) continue;
            if (!byCable.TryGetValue(cableId, out var lst))
            {
                lst = new List<(CableLink, int, int, RackDeviceKind)>();
                byCable[cableId] = lst;
            }

            lst.Add((link, kv.Value.deviceIndex, kv.Value.portIndex, kv.Value.kind));
        }

        var positions = CablePositions.instance;
        var sourceTr = sourceRack.transform;

        foreach (var pair in byCable)
        {
            // Both endpoints must terminate on a device inside this rack.
            if (pair.Value.Count < 2)
            {
                continue;
            }

            var a = pair.Value[0];
            var b = pair.Value[1];

            float speed = 0f;
            Color color = Color.white;
            float length = 0f;
            var localRoute = new List<Vec3>();
            bool fullyInside = true;
            int sfpA = -1, sfpB = -1;

            try
            {
                speed = a.link.connectionSpeed;
            }
            catch
            {
                /* non-fatal */
            }

            try
            {
                sfpA = a.link.sfpTypeInserted;
            }
            catch
            {
                // ignored
            }

            try
            {
                sfpB = b.link.sfpTypeInserted;
            }
            catch
            {
                // ignored
            }

            try
            {
                if (positions)
                {
                    var mat = positions.GetCableMaterial(pair.Key);
                    if (mat) color = mat.color;

                    // GetCablePositions is the complete generated centreline used by
                    // RedrawCable/CreateTubeMesh. In the current game it contains the
                    // extra corner-bend samples produced from raw cable/link positions.
                    // The old implementation merely used this list for length and then
                    // preferred GetRawLinkTransforms; for an unhooked curved cable those
                    // transforms are often only the two ports, so the pasted cable became
                    // a flat A-to-B segment. Preserve every final-path point—downsampling
                    // also visibly flattens tight corners.
                    var finalPath = positions.GetCablePositions(pair.Key);
                    if (finalPath is not null && finalPath.Count >= 2)
                    {
                        Vector3? previous = null;
                        for (var i = 0; i < finalPath.Count; i++)
                        {
                            var point = finalPath[i];
                            localRoute.Add(Vec3.From(sourceTr.InverseTransformPoint(point)));
                            if (previous.HasValue) length += Vector3.Distance(previous.Value, point);
                            previous = point;
                        }
                    }

                    // A cable can briefly have no generated path while it is being
                    // edited. The raw cable positions retain its intersection/control
                    // points and are a much better fallback than endpoint transforms.
                    if (localRoute.Count < 2)
                    {
                        var rawPath = positions.GetRawCablePositions(pair.Key);
                        if (rawPath is not null && rawPath.Count >= 2)
                        {
                            Vector3? previous = null;
                            for (var i = 0; i < rawPath.Count; i++)
                            {
                                var point = rawPath[i];
                                localRoute.Add(Vec3.From(sourceTr.InverseTransformPoint(point)));
                                if (previous.HasValue) length += Vector3.Distance(previous.Value, point);
                                previous = point;
                            }
                        }
                    }

                    // Last-resort compatibility fallback for older CablePositions
                    // implementations which expose transforms but no raw point list.
                    if (localRoute.Count < 2)
                    {
                        var rawTransforms = positions.GetRawLinkTransforms(pair.Key);
                        var rawCount = rawTransforms?.Count ?? 0;
                        if (rawTransforms is not null && rawCount >= 2)
                        {
                            for (var i = 0; i < rawCount; i++)
                            {
                                var tr = rawTransforms[i];
                                if (tr)
                                    localRoute.Add(Vec3.From(sourceTr.InverseTransformPoint(tr.position)));
                            }
                        }
                    }

                    // We accept the cable as long as we have at least the two endpoints.
                    fullyInside = localRoute.Count >= 2;
                }
            }
            catch (Exception ex)
            {
                MelonLogger.Warning($"Cable route capture failed for cableId={pair.Key}: {ex.Message}");
                fullyInside = false;
            }

            // Reject cables whose route leaves the rack – the user explicitly does not
            // want partial cables that depend on hooks outside the rack.
            if (!fullyInside || localRoute.Count < 2)
            {
                continue;
            }

            int typeA = 0, typeB = 0;
            try
            {
                typeA = (int)a.link.typeOfLink;
            }
            catch
            {
                /* ignore */
            }

            try
            {
                typeB = (int)b.link.typeOfLink;
            }
            catch
            {
                /* ignore */
            }

            cables.Add(new RackCableTemplate
            {
                EndA = new RackCableEndpoint { DeviceIndex = a.devIdx, PortIndex = a.port },
                EndB = new RackCableEndpoint { DeviceIndex = b.devIdx, PortIndex = b.port },
                Speed = speed,
                Length = length,
                LocalRoute = localRoute,
                FullyInsideSourceRack = fullyInside,
                TypeA = typeA,
                TypeB = typeB,
                SfpTypeA = sfpA,
                SfpTypeB = sfpB,
                ColorR = color.r,
                ColorG = color.g,
                ColorB = color.b,
                ColorA = color.a
            });
        }

        return cables;
    }

    private static Il2CppReferenceArray<CableLink> GetCableLinkPorts(DeviceWithRuntime d)
    {
        if (d.Server) return d.Server.cablelinks;
        if (d.Switch) return d.Switch.cableLinkSwitchPorts;
        if (d.Patch) return d.Patch.cableLinkPorts;
        return null;
    }

