    private static GameObject ResolvePrefab(RackDeviceTemplate template)
    {
        var mainGameManager = MainGameManager.instance;
        if (!mainGameManager)
            return null;

        return template.Kind switch
        {
            RackDeviceKind.Server => ResolveExactPrefab(mainGameManager.serverPrefabs, template) ??
                                     mainGameManager.GetServerPrefab(template.ServerType),
            RackDeviceKind.NetworkSwitch => ResolveExactPrefab(mainGameManager.switchesPrefabs, template) ??
                                            mainGameManager.GetSwitchPrefab(template.VariantId),
            RackDeviceKind.Router => ResolveExactPrefab(mainGameManager.routersPrefabs, template) ??
                                     mainGameManager.GetRouterPrefab(template.VariantId),
            RackDeviceKind.Firewall => ResolveExactPrefab(mainGameManager.firewallsPrefabs, template) ??
                                       mainGameManager.GetFirewallPrefab(template.VariantId),
            RackDeviceKind.PatchPanel => ResolveExactPrefab(mainGameManager.patchPanelsPrefabs, template) ??
                                         mainGameManager.GetPatchPanelPrefab(template.VariantId),
            _ => null
        };
    }

    /// <summary>
    /// Resolves prefab identity independently from the component's operational type.
    /// Prefer the captured array index when it still matches, then scan by prefabID
    /// and U-size so templates remain valid if a game update reorders the arrays.
    /// </summary>
    private static GameObject ResolveExactPrefab(Il2CppReferenceArray<GameObject> prefabs,
        RackDeviceTemplate template)
    {
        if (prefabs is null) return null;

        if (template.PrefabArrayIndex >= 0 && template.PrefabArrayIndex < prefabs.Count)
        {
            var indexed = prefabs[template.PrefabArrayIndex];
            if (PrefabSizeMatches(indexed, template))
                return indexed;
        }

        GameObject idOnlyMatch = null;
        GameObject sizeOnlyMatch = null;
        var sizeMatchCount = 0;
        for (var i = 0; i < prefabs.Count; i++)
        {
            var candidate = prefabs[i];
            if (PrefabSizeMatches(candidate, template))
            {
                sizeOnlyMatch = candidate;
                sizeMatchCount++;
            }

            if (!PrefabMatches(candidate, template, false)) continue;
            idOnlyMatch ??= candidate;
            if (PrefabMatches(candidate, template, true))
                return candidate;
        }

        // Legacy/template compatibility: prefabID has historically also been the
        // subtype array index. Validate physical size before accepting it.
        if (template.PrefabId >= 0 && template.PrefabId < prefabs.Count)
        {
            var indexedById = prefabs[template.PrefabId];
            if (PrefabSizeMatches(indexedById, template))
                return indexedById;
        }

        if (sizeMatchCount == 1) return sizeOnlyMatch;
        return idOnlyMatch;
    }

    private static bool PrefabMatches(GameObject prefab, RackDeviceTemplate template, bool requireSize)
    {
        if (!prefab) return false;
        var usableObject = prefab.GetComponent<UsableObject>();
        if (!usableObject || usableObject.prefabID != template.PrefabId) return false;
        return !requireSize ||
               Math.Max(1, usableObject.sizeInU) == Math.Max(1, template.SizeInU);
    }

    private static bool PrefabSizeMatches(GameObject prefab, RackDeviceTemplate template)
    {
        if (!prefab) return false;
        var usableObject = prefab.GetComponent<UsableObject>();
        return usableObject &&
               Math.Max(1, usableObject.sizeInU) == Math.Max(1, template.SizeInU);
    }

    private static bool TrySpawnIntoRack(Rack rack, RackDeviceTemplate template, out string message)
    {
        message = string.Empty;

        try
        {
            var sizeU = Math.Max(1, template.SizeInU);
            var anchorPhysicalSlot = ResolveAnchorPhysicalSlot(template.StartIndex, sizeU);
            if (rack.positions is null || template.StartIndex < 0 || anchorPhysicalSlot >= rack.positions.Count)
            {
                message = $"{template.DisplayName}: invalid target position.";
                return false;
            }

            // template.StartIndex is the physically lower occupied slot (0 = bottom)
            // for UI/occupancy planning. Vanilla mounting uses the physically upper
            // slot as the RackPosition anchor and passes that anchor's array index to
            // IsPositionAvailable / MarkPositionAsUsed. If we initialize UID on the
            // lower slot but mark from the upper array index, Rack.MarkPositionAsUsed
            // writes -1 owners into isPositionUsed[] and reload loses server occupancy.
            var arrayStart = ResolveAnchorArrayIndex(rack, template.StartIndex, sizeU);
            if (arrayStart < 0)
            {
                message = $"{template.DisplayName}: invalid target position.";
                return false;
            }

            var available = rack.IsPositionAvailable(arrayStart, sizeU);
            if (!available)
            {
                message = $"{template.DisplayName}: target slots are not free.";
                return false;
            }

            var rackPosition = GetPositionByPhysicalSlot(rack, anchorPhysicalSlot);
            if (!rackPosition)
            {
                message = $"{template.DisplayName}: RackPosition is missing.";
                return false;
            }

            var prefab = ResolvePrefab(template);
            if (!prefab)
            {
                message = $"{template.DisplayName}: no matching prefab found.";
                return false;
            }

            // CRITICAL: instantiate the prefab in DEACTIVATED state so the device's
            // Awake()/Start() do not run before we have wired up currentRackPosition,
            // rackPositionUID, prefabID, sizeInU, label, parent etc. If Awake fired
            // first with currentRackPosition==null, ValidateRackPosition() reports
            // the device as "lost" and the game respawns it at
            // MainGameManager.placeToRespawnLostUsableObjects -> the device falls
            // out of the rack and currentRackPosition stays null forever, which
            // makes BuildDeviceMap drop it -> mod's floor-map shows the rack as
            // empty even though the GameObject exists somewhere in the world.
            var prefabWasActive = false;
            try
            {
                prefabWasActive = prefab.activeSelf;
            }
            catch
            {
                /* defensive */
            }

            try
            {
                if (prefabWasActive) prefab.SetActive(false);
            }
            catch
            {
                /* non-fatal */
            }

            GameObject instance;
            try
            {
                // Parent under MainGameManager.parentUsableObjects when available -
                // that is where the vanilla insert-flow places mounted devices. As a
                // fallback we use the rack-position transform.
                Transform parentTr = null;
                try
                {
                    parentTr = MainGameManager.instance?.parentUsableObjects;
                }
                catch
                {
                    /* fallback */
                }

                if (!parentTr) parentTr = rackPosition.transform;
                instance = Object.Instantiate(prefab, parentTr);
                if (!instance)
                {
                    message = $"{template.DisplayName}: prefab instantiation failed.";
                    return false;
                }

                // Ensure instance is inactive even if prefab.SetActive() above failed
                // (Object.Instantiate copies activeSelf from the prefab).
                try
                {
                    if (instance.activeSelf) instance.SetActive(false);
                }
                catch
                {
                    /* non-fatal */
                }
            }
            finally
            {
                try
                {
                    if (prefabWasActive) prefab.SetActive(true);
                }
                catch
                {
                    /* non-fatal */
                }
            }

            var usableObject = instance.GetComponent<UsableObject>();
            if (!usableObject)
            {
                Object.Destroy(instance);
                message = $"{template.DisplayName}: UsableObject component is missing.";
                MelonLogger.Warning($"{message}");
                return false;
            }

            // Wire up everything the *InsertedInRack methods will look at while we
            // are still INACTIVE (Awake has not run yet). After SetActive(true),
            // Awake sees a fully populated UsableObject.
            EnsureValidRackPositionUid(rackPosition);
            usableObject.currentRackPosition = rackPosition;
            usableObject.rackPositionUID = rackPosition.rackPosGlobalUID;
            usableObject.prefabID = template.PrefabId;
            usableObject.sizeInU = Math.Max(1, template.SizeInU);
            usableObject.labelText = template.Label;

            // Initial pose: identity in rack-position local space; we reapply the
            // captured pose AFTER InsertedInRack because the game centers the device
            // on the slot's anchor inside its own insert routine.
            instance.transform.localPosition = Vector3.zero;
            instance.transform.localRotation = Quaternion.identity;

            // NOTE: Rack.MarkPositionAsUsed / RackPosition.SetUsed are called LATER
            // (after *InsertedInRack), mirroring the vanilla RackPosition.InsertItemInRack
            // coroutine which marks the bitmap as its FINAL step. Calling it pre-activate
            // gets clobbered by something in the activation / Awake / *InsertedInRack
            // sequence — that is why "pickup + reseat" used to be the only way to fix
            // occupancy: reseating runs the real coroutine, which marks the bitmap last.

            var targetRackTr = rack.transform;
            var capturedLocalPos = template.LocalPos.ToUnity();
            var capturedLocalEuler = template.LocalEuler.ToUnity();
            var hasLegacyCapturedPose =
                capturedLocalPos.sqrMagnitude > 0.000001f || capturedLocalEuler.sqrMagnitude > 0.000001f;
            var hasCapturedPose = template.HasLocalPose || hasLegacyCapturedPose;

            Quaternion capturedLocalRotation;
            if (template.HasLocalPose)
            {
                capturedLocalRotation = new Quaternion(
                    template.LocalRotationX,
                    template.LocalRotationY,
                    template.LocalRotationZ,
                    template.LocalRotationW);
                var magnitude = Mathf.Sqrt(
                    capturedLocalRotation.x * capturedLocalRotation.x +
                    capturedLocalRotation.y * capturedLocalRotation.y +
                    capturedLocalRotation.z * capturedLocalRotation.z +
                    capturedLocalRotation.w * capturedLocalRotation.w);
                capturedLocalRotation = magnitude > 0.00001f
                    ? new Quaternion(
                        capturedLocalRotation.x / magnitude,
                        capturedLocalRotation.y / magnitude,
                        capturedLocalRotation.z / magnitude,
                        capturedLocalRotation.w / magnitude)
                    : Quaternion.identity;
            }
            else
            {
                // Compatibility with templates created before exact quaternion capture.
                capturedLocalRotation = Quaternion.Euler(capturedLocalEuler);
            }

            // Activate now -> Awake() runs with all fields set.
            try
            {
                instance.SetActive(true);
            }
            catch (Exception ex)
            {
                MelonLogger.Warning($"SetActive failed: {ex.Message}");
            }

            // Mounted devices must NOT have an active rigidbody; otherwise they'd fall
            // out of the rack and the player couldn't pick them up cleanly. The game
            // calls RemoveRigidbody() during its own RackPosition.InsertItemInRack flow.
            try
            {
                usableObject.RemoveRigidbody();
            }
            catch (Exception ex)
            {
                MelonLogger.Warning($"RemoveRigidbody failed: {ex.Message}");
            }

            switch (template.Kind)
            {
                case RackDeviceKind.Server:
                {
                    var server = instance.GetComponent<Server>();
                    if (!server)
                        throw new InvalidOperationException("Server component is missing.");

                    // Pass null = fresh-insert path. The game initializes a unique
                    // ServerID, valid IP, customer assignment, eolTime/timeToBrake
                    // and the broken/warning state for us. Passing a stub
                    // ServerSaveData would take the LOAD path and leave us with
                    // serverID="", customerID=-1 ("error customer"), eolTime=0.
                    server.ServerInsertedInRack();

                    // Defensive: if the fresh-insert path did not generate a unique
                    // ServerID for some reason, do it ourselves. NetworkMap.servers
                    // is keyed by ServerID; a duplicate / empty ID causes the
                    // snapshot ctor to drop entries on save.
                    if (string.IsNullOrEmpty(server.ServerID))
                    {
                        try
                        {
                            var newId = server.GenerateUniqueServerId();
                            if (!string.IsNullOrEmpty(newId)) server.ServerID = newId;
                        }
                        catch (Exception ex)
                        {
                            MelonLogger.Warning($"GenerateUniqueServerId failed: {ex.Message}");
                        }
                    }

                    // Hardware prefab index and operational serverType are distinct
                    // in the updated game. In particular, Yellow2/5U is prefab index
                    // 1 but operational type 0. The old migration assigned index 1
                    // to serverType, preventing the route evaluator from assigning
                    // an application until save/reload reconstructed the prefab.
                    //
                    // We deliberately DO NOT copy the source's IP, customer or appID:
                    // a pasted server should behave like a freshly-bought one (own IP,
                    // own customer assignment). Newly captured templates replay the
                    // source's actual operational type. Legacy templates retain the
                    // correctly serialized value already present on the prefab.
                    try
                    {
                        if (template.HasOperationalServerType &&
                            server.serverType != template.ServerType)
                        {
                            server.serverType = template.ServerType;
                        }
                    }
                    catch (Exception ex)
                    {
                        MelonLogger.Warning($"set serverType failed: {ex.Message}");
                    }

                    if (!string.IsNullOrEmpty(server.ServerID))
                    {
                        PastedServerIds.Add(server.ServerID);
                    }

                    // ButtonClickChangeIP only opens the IP dialog in the updated
                    // game; it does not initialize an address. Leave the fresh server
                    // unconfigured and let the player use the normal SetIP flow.
                    var expectedCapacity = template.ServerMaxProcessingSpeed > 0f
                        ? template.ServerMaxProcessingSpeed
                        : server.maxProcessingSpeed;
                    var serverInstanceId = server.GetInstanceID();
                    PastedServerCapacityByInstance[serverInstanceId] = expectedCapacity;

                    if (!string.IsNullOrEmpty(template.Label)) server.labelText = template.Label;
                    RestoreServerPowerState(server, template.IsPoweredOn);
                    RefreshPastedServerRuntimeState(server);
                    break;
                }
                case RackDeviceKind.NetworkSwitch:
                {
                    var networkSwitch = instance.GetComponent<NetworkSwitch>();
                    if (!networkSwitch)
                        throw new InvalidOperationException("Switch component is missing.");

                    networkSwitch.SwitchInsertedInRack(); // fresh-insert path
                    // Idempotent insurance: if SwitchInsertedInRack already registered
                    // the switch this is a no-op (Dictionary indexer overwrites).
                    try
                    {
                        NetworkMap.instance?.RegisterSwitch(networkSwitch);
                    }
                    catch (Exception ex)
                    {
                        MelonLogger.Warning($"RegisterSwitch failed: {ex.Message}");
                    }

                    RestoreVlanFilters(networkSwitch, template);
                    if (!string.IsNullOrEmpty(template.Label)) networkSwitch.labelText = template.Label;
                    RestoreSwitchPowerState(networkSwitch, template.IsPoweredOn);
                    break;
                }
                case RackDeviceKind.Router:
                {
                    var router = instance.GetComponent<Router>();
                    if (!router)
                        throw new InvalidOperationException("Router component is missing.");

                    // Router overrides SwitchInsertedInRack. The null/fresh path
                    // creates a unique switch ID and initializes base switch state;
                    // Router-specific configuration is then replayed as one snapshot
                    // so route withdrawal/reapplication follows vanilla semantics.
                    router.SwitchInsertedInRack();
                    try
                    {
                        NetworkMap.instance?.RegisterSwitch(router);
                    }
                    catch (Exception ex)
                    {
                        MelonLogger.Warning($"Register router failed: {ex.Message}");
                    }

                    RestoreVlanFilters(router, template);
                    RestoreRouterConfiguration(router, template);
                    if (!string.IsNullOrEmpty(template.Label)) router.labelText = template.Label;
                    RestoreSwitchPowerState(router, template.IsPoweredOn);
                    break;
                }
                case RackDeviceKind.Firewall:
                {
                    var firewall = instance.GetComponent<Firewall>();
                    if (!firewall)
                        throw new InvalidOperationException("Firewall component is missing.");

                    firewall.InsertedInRack();
                    try
                    {
                        NetworkMap.instance?.RegisterSwitch(firewall);
                    }
                    catch (Exception ex)
                    {
                        MelonLogger.Warning($"Register firewall failed: {ex.Message}");
                    }

                    RestoreVlanFilters(firewall, template);
                    RestoreFirewallConfiguration(firewall, template);
                    if (!string.IsNullOrEmpty(template.Label)) firewall.labelText = template.Label;
                    RestoreSwitchPowerState(firewall, template.IsPoweredOn);
                    break;
                }
                case RackDeviceKind.PatchPanel:
                {
                    var patchPanel = instance.GetComponent<PatchPanel>();
                    if (!patchPanel)
                        throw new InvalidOperationException("PatchPanel component is missing.");

                    patchPanel.InsertedInRack(); // fresh-insert path
                    if (!string.IsNullOrEmpty(template.Label)) patchPanel.labelText = template.Label;
                    break;
                }
                default:
                    throw new ArgumentOutOfRangeException();
            }

            // Belt-and-suspenders: re-assert currentRackPosition / UID / prefabID
            // / sizeInU after *InsertedInRack in case the vanilla method overwrote
            // them. This is what makes the mod's floor-map count the slot as used.
            EnsureValidRackPositionUid(rackPosition);
            usableObject.currentRackPosition = rackPosition;
            usableObject.rackPositionUID = rackPosition.rackPosGlobalUID;
            usableObject.prefabID = template.PrefabId;
            usableObject.sizeInU = Math.Max(1, template.SizeInU);

            // ROOT-CAUSE FIX for "pasted rack shows 2/47U occupancy until I reseat".
            // The vanilla RackPosition.InsertItemInRack coroutine marks the slot
            // bitmap (Rack.isPositionUsed[]) as its FINAL step, AFTER the device's
            // *InsertedInRack method has run. Doing it earlier (pre-SetActive or
            // pre-*InsertedInRack) gets clobbered — which is exactly what we
            // observed. Mark NOW, post-insert, exactly like the coroutine does.
            try
            {
                rack.MarkPositionAsUsed(arrayStart, sizeU);
                rackPosition.SetUsed(true);
            }
            catch (Exception ex)
            {
                MelonLogger.Warning($"post-insert MarkPositionAsUsed failed: {ex.Message}");
            }

            // The InsertedInRack methods are required for IDs/state, but their visual
            // placement is based on the newly selected rackPosition and can interpret a
            // multi-U device's top-pivot as the anchor. For copied templates we already
            // captured the exact final rack-local device pose from the source rack.
            // Apply it AFTER the game initialization so there is no second offset and
            // the pasted device visually lands exactly where the copied one was.
            if (hasCapturedPose)
            {
                instance.transform.position = targetRackTr.TransformPoint(capturedLocalPos);
                instance.transform.rotation = targetRackTr.rotation * capturedLocalRotation;
            }
            else if (sizeU > 1)
            {
                var pivotSlot = template.StartIndex + sizeU - 1;
                var pivotRackPosition = GetPositionByPhysicalSlot(rack, pivotSlot);
                if (pivotRackPosition)
                {
                    instance.transform.position = pivotRackPosition.transform.position;
                }
            }

            SyncMountedDeviceWithVanillaState(rack, rackPosition, template, usableObject);

            message = $"{template.DisplayName} inserted (+{CalculateAdjustedPrice(template.BasePrice)}).";
            return true;
        }
        catch (Exception ex)
        {
            message = $"{template.DisplayName}: error while inserting – {ex.Message}";
            MelonLogger.Error($"TrySpawnIntoRack failed: {ex}");
            return false;
        }
    }

