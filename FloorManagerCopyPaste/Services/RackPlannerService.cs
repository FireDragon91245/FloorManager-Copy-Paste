    private sealed class DeviceWithRuntime
    {
        public RackDeviceTemplate Template { get; init; }
        public Server Server { get; init; }
        public NetworkSwitch Switch { get; init; }
        public PatchPanel Patch { get; init; }
    }

    private static Dictionary<Rack, List<DeviceWithRuntime>> BuildDeviceMap()
    {
        var map = new Dictionary<Rack, List<DeviceWithRuntime>>();
        var usableObjects = Object.FindObjectsOfType<UsableObject>();

        foreach (var usableObject in usableObjects)
        {
            if (!usableObject || !usableObject.currentRackPosition ||
                !usableObject.currentRackPosition.rack)
                continue;

            if (!TryBuildDeviceTemplate(usableObject, out var deviceTemplate, out var server, out var sw, out var pp))
                continue;

            var rack = usableObject.currentRackPosition.rack;
            if (!map.TryGetValue(rack, out var list))
            {
                list = new List<DeviceWithRuntime>();
                map[rack] = list;
            }

            list.Add(new DeviceWithRuntime
            {
                Template = deviceTemplate,
                Server = server,
                Switch = sw,
                Patch = pp
            });
        }

        return map;
    }

    /// <summary>
    /// Returns the rack's <c>positions</c> sorted ascending by rack-LOCAL Y, so
    /// index 0 is the physically lowest slot (U01) and index <c>N-1</c> is the topmost.
    /// We use <see cref="Transform.InverseTransformPoint(Vector3)"/> instead of world Y so the
    /// ordering is correct even when the rack is rotated or its prefab places all
    /// slot transforms at the same world Y.
    /// </summary>
    private static List<RackPosition> GetPhysicalOrderPositions(Rack rack)
    {
        var list = new List<RackPosition>();
        if (!rack || rack.positions is null) return list;
        list.AddRange(rack.positions.Where(p => p));

        var rackTr = rack.transform;
        list.Sort((a, b) =>
        {
            float ya = 0f, yb = 0f;
            try
            {
                ya = rackTr.InverseTransformPoint(a.transform.position).y;
            }
            catch
            {
                /* fallback */
            }

            try
            {
                yb = rackTr.InverseTransformPoint(b.transform.position).y;
            }
            catch
            {
                /* fallback */
            }

            return ya.CompareTo(yb);
        });
        return list;
    }

    /// <summary>
    /// Resolves the physical slot (0-based, bottom-to-top) of <paramref name="rackPos"/>.
    /// The game's <c>RackPosition.positionIndex</c> is a logical id that does NOT match
    /// the rendered U-number; sorting by Y does.
    /// </summary>
    private static int ResolveSlotIndex(Rack rack, RackPosition rackPos)
    {
        if (!rack || !rackPos) return -1;
        var ordered = GetPhysicalOrderPositions(rack);
        for (var i = 0; i < ordered.Count; i++)
            if (ordered[i] == rackPos)
                return i;
        return -1;
    }

    /// <summary>Returns the <see cref="RackPosition"/> at a physical slot.</summary>
    private static RackPosition GetPositionByPhysicalSlot(Rack rack, int physicalSlot)
    {
        var ordered = GetPhysicalOrderPositions(rack);
        if (physicalSlot < 0 || physicalSlot >= ordered.Count) return null;
        return ordered[physicalSlot];
    }

    /// <summary>
    /// Translates a physical slot index back to the array index inside
    /// <c>rack.positions</c> (= the index expected by <c>Rack.IsPositionAvailable</c>
    /// and <c>Rack.MarkPositionAsUsed</c>).
    /// </summary>
    private static int PhysicalToArrayIndex(Rack rack, int physicalSlot)
    {
        var pos = GetPositionByPhysicalSlot(rack, physicalSlot);
        if (!pos || rack?.positions is null) return -1;
        for (var i = 0; i < rack.positions.Count; i++)
            if (rack.positions[i] == pos)
                return i;
        return -1;
    }

    /// <summary>
    /// Vanilla uses the physically upper slot of a multi-U device as the device's
    /// <c>currentRackPosition</c> / persisted <c>rackPositionUID</c> anchor. The UI
    /// template stores the physically lower occupied slot so stamping can cover
    /// [bottom…top]. Convert bottom+size to that vanilla anchor slot.
    /// </summary>
    private static int ResolveAnchorPhysicalSlot(int bottomPhysicalSlot, int sizeInU)
        => bottomPhysicalSlot + Math.Max(1, sizeInU) - 1;

    private static int ResolveAnchorArrayIndex(Rack rack, int bottomPhysicalSlot, int sizeInU)
        => PhysicalToArrayIndex(rack, ResolveAnchorPhysicalSlot(bottomPhysicalSlot, sizeInU));

    /// <summary>
    /// Resolve the physically lowest occupied slot for a mounted device from the
    /// vanilla rack owner bitmap. <c>Rack.isPositionUsed[]</c> stores the owning
    /// RackPosition UID in each occupied slot, not a boolean. This is more reliable
    /// for Floor Plan/template capture than guessing from <c>currentRackPosition</c>.
    /// </summary>
    private static int ResolveBottomPhysicalSlotFromOwnerBitmap(Rack rack, RackPosition rackPosition)
    {
        if (!rack || !rackPosition || rack.positions is null || rack.isPositionUsed is null)
            return -1;

        var ownerUid = rackPosition.rackPosGlobalUID;
        if (ownerUid <= 0) return -1;

        var minPhysical = int.MaxValue;
        var matched = 0;
        var count = Math.Min(rack.positions.Count, rack.isPositionUsed.Count);
        for (var arrayIndex = 0; arrayIndex < count; arrayIndex++)
        {
            int owner;
            try
            {
                owner = rack.isPositionUsed[arrayIndex];
            }
            catch
            {
                continue;
            }

            if (owner != ownerUid) continue;

            var pos = rack.positions[arrayIndex];
            var physical = ResolveSlotIndex(rack, pos);
            if (physical < 0) continue;

            minPhysical = Math.Min(minPhysical, physical);
            matched++;
        }

        if (matched <= 0) return -1;
        return minPhysical == int.MaxValue ? -1 : minPhysical;
    }

    private static bool TryBuildDeviceTemplate(UsableObject usableObject, out RackDeviceTemplate template,
        out Server server, out NetworkSwitch sw, out PatchPanel patch)
    {
        template = null;
        server = null;
        sw = null;
        patch = null;

        var rackPos = usableObject.currentRackPosition;
        var anchorIndex = ResolveSlotIndex(rackPos?.rack, rackPos);
        if (anchorIndex < 0) return false;
        var sizeInU = Math.Max(1, usableObject.sizeInU);
        var bitmapStartIndex = ResolveBottomPhysicalSlotFromOwnerBitmap(rackPos?.rack, rackPos);
        var startIndex = bitmapStartIndex >= 0 ? bitmapStartIndex : Math.Max(0, anchorIndex - sizeInU + 1);
        var label = usableObject.labelText ?? string.Empty;
        var shopItem = usableObject.shopItemSO;
        var displayName = shopItem?.itemName ?? usableObject.gameObject.name;
        var basePrice = shopItem?.price ?? 0;
        var prefabId = usableObject.prefabID;

        // Capture the EXACT placement in source rack-local space so we can replay it
        // pixel-perfect on a target rack (same prefab → same local-to-world mapping).
        // This sidesteps any guesswork about prefab pivot / rack-position anchor offsets.
        var rackTr = rackPos?.rack?.transform;
        var localPos = rackTr
            ? Vec3.From(rackTr.InverseTransformPoint(usableObject.transform.position))
            : default;
        var localRotation = rackTr
            ? Quaternion.Inverse(rackTr.rotation) * usableObject.transform.rotation
            : Quaternion.identity;
        var localEuler = Vec3.From(localRotation.eulerAngles);
        server = usableObject.GetComponent<Server>();
        if (server)
        {
            var prefabArrayIndex =
                FindPrefabArrayIndex(MainGameManager.instance?.serverPrefabs, usableObject);
            var exactPrefabIndex = prefabArrayIndex >= 0 ? prefabArrayIndex : -1;
            template = new RackDeviceTemplate
            {
                Kind = RackDeviceKind.Server,
                StartIndex = startIndex,
                SizeInU = sizeInU,
                PrefabId = prefabId,
                PrefabArrayIndex = prefabArrayIndex,
                VariantId = exactPrefabIndex,
                BasePrice = basePrice,
                DisplayName = displayName,
                Label = label,
                IsPoweredOn = server.isOn,
                LocalPos = localPos,
                LocalEuler = localEuler,
                HasLocalPose = rackTr,
                LocalRotationX = localRotation.x,
                LocalRotationY = localRotation.y,
                LocalRotationZ = localRotation.z,
                LocalRotationW = localRotation.w,
                // Hardware identity and operational type are deliberately separate.
                // Yellow2/5U is serverPrefabs[1] but has serverType 0.
                ServerType = server.serverType,
                HasOperationalServerType = true,
                ServerMaxProcessingSpeed = server.maxProcessingSpeed
            };
            return true;
        }

        var firewall = usableObject.GetComponent<Firewall>();
        if (firewall)
        {
            sw = firewall;
            var prefabArrayIndex =
                FindPrefabArrayIndex(MainGameManager.instance?.firewallsPrefabs, usableObject);
            template = new RackDeviceTemplate
            {
                Kind = RackDeviceKind.Firewall,
                StartIndex = startIndex,
                SizeInU = sizeInU,
                PrefabId = prefabId,
                PrefabArrayIndex = prefabArrayIndex,
                VariantId = firewall.switchType,
                BasePrice = basePrice,
                DisplayName = displayName,
                Label = label,
                IsPoweredOn = firewall.isOn,
                LocalPos = localPos,
                LocalEuler = localEuler,
                HasLocalPose = rackTr,
                LocalRotationX = localRotation.x,
                LocalRotationY = localRotation.y,
                LocalRotationZ = localRotation.z,
                LocalRotationW = localRotation.w,
                PortVlanFilters = CaptureVlanFilters(firewall),
                FirewallClusterIp = firewall.clusterIP ?? string.Empty,
                FirewallRules = CaptureFirewallRules(firewall)
            };
            return true;
        }

        var router = usableObject.GetComponent<Router>();
        if (router)
        {
            sw = router;
            var prefabArrayIndex =
                FindPrefabArrayIndex(MainGameManager.instance?.routersPrefabs, usableObject);
            template = new RackDeviceTemplate
            {
                Kind = RackDeviceKind.Router,
                StartIndex = startIndex,
                SizeInU = sizeInU,
                PrefabId = prefabId,
                PrefabArrayIndex = prefabArrayIndex,
                VariantId = router.switchType,
                BasePrice = basePrice,
                DisplayName = displayName,
                Label = label,
                IsPoweredOn = router.isOn,
                LocalPos = localPos,
                LocalEuler = localEuler,
                HasLocalPose = rackTr,
                LocalRotationX = localRotation.x,
                LocalRotationY = localRotation.y,
                LocalRotationZ = localRotation.z,
                LocalRotationW = localRotation.w,
                PortVlanFilters = CaptureVlanFilters(router),
                RouterAsn = router.asn,
                RouterNextRouteId = Math.Max(1, router.nextRouteId),
                RouterOwnedSubnets = CaptureRouterOwnedSubnets(router),
                RouterRoutes = CaptureRouterRoutes(router)
            };
            return true;
        }

        sw = usableObject.GetComponent<NetworkSwitch>();
        if (sw)
        {
            var prefabArrayIndex =
                FindPrefabArrayIndex(MainGameManager.instance?.switchesPrefabs, usableObject);
            template = new RackDeviceTemplate
            {
                Kind = RackDeviceKind.NetworkSwitch,
                StartIndex = startIndex,
                SizeInU = sizeInU,
                PrefabId = prefabId,
                PrefabArrayIndex = prefabArrayIndex,
                VariantId = sw.switchType,
                BasePrice = basePrice,
                DisplayName = displayName,
                Label = label,
                IsPoweredOn = sw.isOn,
                LocalPos = localPos,
                LocalEuler = localEuler,
                HasLocalPose = rackTr,
                LocalRotationX = localRotation.x,
                LocalRotationY = localRotation.y,
                LocalRotationZ = localRotation.z,
                LocalRotationW = localRotation.w,
                PortVlanFilters = CaptureVlanFilters(sw)
            };
            return true;
        }

        patch = usableObject.GetComponent<PatchPanel>();
        if (patch)
        {
            // Patch panels are visually 2U in this game; usableObject.sizeInU is sometimes
            // reported as 1, so we clamp to a minimum of 2 to keep blueprints/sidebar
            // accurate – but only when there is actually room in the rack, otherwise
            // we'd push the device past the top edge and BuildPreview would reject it.
            var totalSlots = rackPos?.rack?.positions?.Count ?? int.MaxValue;
            var ppSize = Math.Max(2, sizeInU);
            if (startIndex + ppSize > totalSlots) ppSize = Math.Max(1, totalSlots - startIndex);
            var prefabArrayIndex =
                FindPrefabArrayIndex(MainGameManager.instance?.patchPanelsPrefabs, usableObject);
            template = new RackDeviceTemplate
            {
                Kind = RackDeviceKind.PatchPanel,
                StartIndex = startIndex,
                SizeInU = ppSize,
                PrefabId = prefabId,
                PrefabArrayIndex = prefabArrayIndex,
                VariantId = patch.patchPanelType,
                BasePrice = basePrice,
                DisplayName = displayName,
                Label = label,
                IsPoweredOn = false,
                LocalPos = localPos,
                LocalEuler = localEuler,
                HasLocalPose = rackTr,
                LocalRotationX = localRotation.x,
                LocalRotationY = localRotation.y,
                LocalRotationZ = localRotation.z,
                LocalRotationW = localRotation.w
            };
            return true;
        }

        return false;
    }

    /// <summary>
    /// Finds the exact source prefab by persistent prefabID and physical U-size.
    /// The updated game can leave Server.serverType at zero even when the mounted
    /// instance came from a later prefab entry, so serverType alone is not identity.
    /// </summary>
    private static int FindPrefabArrayIndex(Il2CppReferenceArray<GameObject> prefabs, UsableObject source)
    {
        if (prefabs is null || !source) return -1;

        var idOnlyMatch = -1;
        var sizeOnlyMatch = -1;
        var sizeMatchCount = 0;
        for (var i = 0; i < prefabs.Count; i++)
        {
            var prefab = prefabs[i];
            if (!prefab) continue;

            var candidate = prefab.GetComponent<UsableObject>();
            if (!candidate) continue;

            var sameSize = Math.Max(1, candidate.sizeInU) == Math.Max(1, source.sizeInU);
            if (sameSize)
            {
                sizeOnlyMatch = i;
                sizeMatchCount++;
            }

            // The shared ShopItemSO is the strongest identity when present.
            if (sameSize && source.shopItemSO && candidate.shopItemSO == source.shopItemSO)
                return i;

            if (candidate.prefabID != source.prefabID) continue;
            if (idOnlyMatch < 0) idOnlyMatch = i;
            if (sameSize) return i;
        }

        // In several game builds prefabID is the array/subtype index assigned by
        // the shop, while the prefab asset's own UsableObject still contains zero.
        if (source.prefabID >= 0 && source.prefabID < prefabs.Count)
        {
            var indexed = prefabs[source.prefabID];
            var indexedUsable = indexed ? indexed.GetComponent<UsableObject>() : null;
            if (indexedUsable &&
                Math.Max(1, indexedUsable.sizeInU) == Math.Max(1, source.sizeInU))
                return source.prefabID;
        }

        if (sizeMatchCount == 1) return sizeOnlyMatch;
        return idOnlyMatch;
    }

    private static List<NetworkPortVlanFilterTemplate> CaptureVlanFilters(NetworkSwitch networkSwitch)
    {
        var result = new List<NetworkPortVlanFilterTemplate>();
        if (!networkSwitch || networkSwitch.disallowedVlansPerPort is null) return result;

        foreach (var entry in networkSwitch.disallowedVlansPerPort)
        {
            var vlanIds = new List<int>();
            if (entry.Value is not null)
            {
                foreach (var vlanId in entry.Value)
                    vlanIds.Add(vlanId);
            }

            result.Add(new NetworkPortVlanFilterTemplate
            {
                PortIndex = entry.Key,
                DisallowedVlanIds = vlanIds
            });
        }

        return result;
    }

